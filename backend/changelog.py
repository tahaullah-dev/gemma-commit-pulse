"""Markdown changelog generation from a completed analysis."""
from __future__ import annotations

CATEGORY_META = {
    "feature": ("🚀", "Features"),
    "fix": ("🐛", "Bug Fixes"),
    "refactor": ("♻️", "Refactoring"),
    "performance": ("⚡", "Performance"),
    "security": ("🔒", "Security"),
    "docs": ("📝", "Documentation"),
    "test": ("✅", "Tests"),
    "chore": ("🧹", "Chores"),
    "dependency": ("📦", "Dependencies"),
    "breaking": ("💥", "Breaking Changes"),
}

STATUS_LABEL = {
    "added": "added",
    "modified": "modified",
    "deleted": "deleted",
    "renamed": "renamed",
}


def _escape_cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def build_changelog(analysis: dict, facts: dict, meta: dict) -> str:
    stats = facts.get("stats", {})
    title = meta.get("title") or "Release Notes"
    lines: list[str] = [f"# {title}", ""]

    risk_line = (
        f"> Generated by **GemmaCommit Pulse** · {meta.get('created_at', '')} · "
        f"Risk **{analysis.get('risk_level', 'n/a')}** "
        f"({analysis.get('risk_score', 0)}/100) · "
        f"Confidence **{analysis.get('confidence', 'n/a')}**"
    )
    lines += [risk_line, ""]

    summary = analysis.get("executive_summary")
    if summary:
        lines += ["## Summary", "", summary, ""]

    for category in analysis.get("categories", []):
        icon, label = CATEGORY_META.get(category.get("name"), ("•", category.get("name", "Changes").title()))
        items = category.get("items") or []
        if not items:
            continue
        lines += [f"## {icon} {label}", ""]
        lines += [f"- {item}" for item in items]
        lines.append("")

    breaking = analysis.get("breaking_changes") or []
    if breaking:
        lines += ["## 💥 Breaking Changes", ""]
        for entry in breaking:
            detail = entry.get("detail", "")
            migration = entry.get("migration", "")
            if migration:
                lines.append(f"- **{detail}** — _Migration:_ {migration}")
            else:
                lines.append(f"- **{detail}**")
        lines.append("")

    security = analysis.get("security_observations") or []
    if security:
        lines += ["## 🔒 Security Notes", ""]
        for entry in security:
            location = f" (`{entry['file']}`)" if entry.get("file") else ""
            lines.append(f"- **[{entry.get('severity', 'info')}]** {entry.get('detail', '')}{location}")
        lines.append("")

    bugs = analysis.get("potential_bugs") or []
    if bugs:
        lines += ["## ⚠️ Potential Issues", ""]
        for entry in bugs:
            location = f" (`{entry['file']}`)" if entry.get("file") else ""
            lines.append(f"- **[{entry.get('severity', 'info')}]** {entry.get('detail', '')}{location}")
        lines.append("")

    files = facts.get("files") or []
    if files:
        lines += [f"## 🧾 Files Changed ({stats.get('files_changed', len(files))})", ""]
        lines += ["| File | Change | + | − |", "| --- | --- | ---: | ---: |"]
        for f in files:
            lines.append(
                f"| `{_escape_cell(f['path'])}` | {STATUS_LABEL.get(f['status'], f['status'])} "
                f"| {f['additions']} | {f['deletions']} |"
            )
        lines.append("")
        lines.append(
            f"**Totals:** +{stats.get('additions', 0)} / −{stats.get('deletions', 0)} "
            f"across {stats.get('files_changed', 0)} file(s)."
        )
        lines.append("")

    lines += ["---", ""]
    if meta.get("mode") == "ai":
        lines.append(f"*Analysis by `{meta.get('model')}`. Diff facts verified programmatically.*")
    else:
        lines.append("*Analysis produced by the offline heuristic engine (no model call).*")

    return "\n".join(lines).strip() + "\n"